"""Render the SPCS service specifications for one FLIP trust (FLIP#1582).

Reads the trust's kit file (``trust/.env.<CODE>.<env>``) and writes one specification
per service in the naming contract into ``rendered/<CODE>.<env>/``, plus a
``manifest.json`` describing what was rendered (service names, compute pools, mapped
secret OBJECT NAMES, volumes and their read-only intent). The Makefile's ``up`` target
reads that manifest to know which SQL to emit, and the spec guards assert against it.

Nothing written here is a secret. Credentials reach containers only as Snowflake SECRET
objects, whose values ``make sync-kit`` writes; a kit value that is a credential is
never interpolated into a rendered file. The guards in ``tests/`` assert that directly.

Usage:
  python3 render_specs.py --kit GSTT --env production
  python3 render_specs.py --kit GSTT --env production --out-dir /tmp/specs
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import yaml_min  # noqa: E402
from kitfile import is_placeholder, kit_path, read_env_vars, resolve_env  # noqa: E402
from mirror_images import source_tag  # noqa: E402
from naming import FL_CLIENT_IMAGES, Names, NamingError, fl_client_image  # noqa: E402
from spec_templates import build_all  # noqa: E402

REPO_ROOT = HERE.parents[2]

#: Where ``make mirror-images`` records the digest it pushed for each repository.
IMAGE_LOCK = "images.lock.json"

HEADER = """\
# ── Generated by render_specs.py - DO NOT edit by hand ──────────────────────
# SPCS service specification for '{service}' of FLIP trust {code} ({env}).
# Rendered from trust/.env.{code}.{env}. Contains NO secret values: credentials
# reach the container as Snowflake SECRET objects, written by `make sync-kit`.
# Regenerate with:
#   make -C trust/deploy/snowflake render KIT={code} HUB=<env>
"""


def load_digests(directory: Path, code: str, env: str, kit: dict[str, str]) -> dict[str, str]:
    """Image digests ``make mirror-images`` recorded for this trust at the kit's tags.

    There is one lock per checkout, so it is used only when it was written for this trust
    and environment. An image mirrored at another tag than the kit now asks for is refused:
    that tag is not in the account repository, so its service could not pull it.
    """
    lock = directory / IMAGE_LOCK
    if not lock.exists():
        return {}
    try:
        data = json.loads(lock.read_text())
    except json.JSONDecodeError as e:
        sys.exit(f"❌ {lock} is not valid JSON ({e}). Re-run `make mirror-images`.")
    if (data.get("code"), data.get("env")) != (code, env):
        print(f"   ⚠  {IMAGE_LOCK} is for {data.get('code')} ({data.get('env')}), not {code} ({env}): not used.")
        print("      Run `make mirror-images` for this trust.")
        return {}
    # A kit that switched FL backend keeps the old client's entry in the lock for good.
    other_clients = set(FL_CLIENT_IMAGES.values()) - {fl_client_image(kit)}
    digests: dict[str, str] = {}
    stale: list[str] = []
    for repo, entry in data.get("images", {}).items():
        if repo in other_clients:
            continue
        asked = source_tag(kit, repo)
        if entry.get("tag") == asked:
            digests[repo] = entry.get("digest", "")
        else:
            stale.append(f"{repo}:{asked}")
    if stale:
        sys.exit(f"❌ Not mirrored at the kit's tag: {', '.join(stale)}. Run `make mirror-images` first.")
    return digests


def render(kit: dict[str, str], code: str, env: str, out_dir: Path, digests: dict[str, str]) -> dict[str, Any]:
    """Write every service specification and the manifest. Returns the manifest."""
    names = Names(code)
    # Built before anything is cleared, so a refused kit leaves the previous specs in place.
    rendered = build_all(kit, code, digests)
    out_dir.mkdir(parents=True, exist_ok=True)
    # A stale spec from a previous render (an FL net removed from the kit, say) would
    # otherwise still be deployed by `up`, which walks the manifest - and still sit in
    # the directory an operator reads. Clear what we own, nothing else.
    for stale in out_dir.glob("*.yaml"):
        stale.unlink()

    services: list[dict[str, Any]] = []
    for item in rendered:
        path = out_dir / f"{item.name}.yaml"
        body = HEADER.format(service=item.name, code=names.code, env=env) + yaml_min.dump(item.spec)
        path.write_text(body)
        container = item.spec["spec"]["containers"][0]
        services.append(
            {
                "name": item.name,
                "sql_name": names.service(item.name),
                "kind": item.kind,
                # The role that creates the service, and so the role of the token its
                # container is handed. The FL client runs researcher code: it gets its own.
                "role": names.fl_role if item.name.startswith("fl-client") else names.service_role,
                "pool": item.pool,
                "spec_file": path.name,
                "image": container["image"],
                "secrets": sorted(entry["snowflakeSecret"]["objectName"] for entry in container.get("secrets", [])),
                "volumes": [volume["name"] for volume in item.spec["spec"].get("volumes", [])],
                "read_only_volumes": item.read_only_volumes,
                "endpoints": item.spec["spec"].get("endpoints", []),
                "external_access_integrations": item.external_access_integrations,
            }
        )

    manifest: dict[str, Any] = {
        "code": names.code,
        "env": env,
        "database": names.database,
        # The role every deploy statement runs as: the least-privilege workload role, which
        # owns the database, the pools, the repository, the stages, the secrets and the
        # services (epic FLIP#1589). FLIP_<CODE>_ADMIN is retired.
        "role": names.deploy_role,
        # Services are created AS this role so their tokens carry its grants (FLIP#1578).
        "service_role": names.service_role,
        "fl_role": names.fl_role,
        "schema": "APP",
        "warehouse": names.warehouse,
        "image_repository": names.image_repository,
        "image_repository_path": names.image_repository_path,
        "pools": {"service": names.pool, "job": names.job_pool, "gpu": names.gpu_pool},
        # Empty unless the platform tier was applied with enable_hub_egress (#1599/#1586).
        "external_access_integrations": sorted(
            {name for service in services for name in service["external_access_integrations"]}
        ),
        "services": services,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    if is_placeholder(kit.get("XNAT_DATA_PASSWORD", "")):
        # Not an error (FLIP#2011): imaging-api starts and the rest of the trust works. It is the one thing
        # a deploy from this kit leaves broken, so say so at the step the operator is looking at.
        print(
            "⚠️  The kit has no XNAT_DATA_PASSWORD, so the XNAT data account is left out: imaging-api will refuse "
            "downloads and uploads (503) until it is set. Run make generate-xnat-credentials KIT=<CODE>, then "
            "sync-kit, render, up and the xnat-configure job.",
            file=sys.stderr,
        )
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Render SPCS service specs for a FLIP trust")
    parser.add_argument("--kit", required=True, help="Trust CODE (e.g. GSTT)")
    parser.add_argument(
        "--env",
        default=None,
        help="Kit-file env token (trust/.env.<KIT>.<token>). Required when HUB is set; the "
        "Makefile injects it from deploy/env_mode.mk. Default without HUB: development.",
    )
    parser.add_argument("--out-dir", type=Path, default=None, help="Output directory (default: rendered/<KIT>.<env>)")
    parser.add_argument(
        "--kit-file",
        type=Path,
        default=None,
        help="Read the kit from this file instead of trust/.env.<KIT>.<env> (tests, dry runs)",
    )
    args = parser.parse_args()

    # The kit is the one place that holds the switch: a value given for one run is gone on
    # the next, whose `up` then detaches the trust. Make exports a make-line value too.
    if "HUB_EGRESS" in os.environ:
        sys.exit(
            "❌ HUB_EGRESS is set on the make line or in the environment. It is read from the kit file\n"
            "   only: put HUB_EGRESS=true (or false) in trust/.env.<CODE>.<env> and run again without it."
        )
    env = resolve_env(args.env)
    try:
        names = Names(args.kit)
    except NamingError as e:
        sys.exit(f"❌ {e}")

    path = args.kit_file or kit_path(REPO_ROOT, args.kit, env)
    if not path.exists():
        sys.exit(
            f"❌ Kit file not found: {path}\n"
            "   Register the trust first:\n"
            f'     make new-trust TRUST_CODE={args.kit} TRUST_NAME="..."\n'
            f"     make -C deploy/aws register-trusts KIT={args.kit} HUB={env}\n"
            f"     make sync-trust-kit KIT={args.kit} HUB={env}"
        )
    kit = read_env_vars(path)
    out_dir = args.out_dir or HERE / "rendered" / f"{names.code}.{env}"
    try:
        digests = load_digests(HERE, names.code, env, kit)
        manifest = render(kit, args.kit, env, out_dir, digests)
    except ValueError as e:
        sys.exit(f"❌ {e}")

    print(f"🔧 Rendered {len(manifest['services'])} SPCS specs for {names.code} ({env})")
    print(f"   Kit file: {path}")
    print(f"   Output:   {out_dir}")
    if not digests:
        print("   ⚠  No image digests for this trust - specs reference images by TAG. Run `make mirror-images`")
        print("      before deploying anything you intend to keep: a tag in the account repository")
        print("      can be moved, a digest cannot.")
    for service in manifest["services"]:
        print(f"   • {service['name']:<20} {service['kind']:<8} pool={service['pool']}")


if __name__ == "__main__":
    main()
