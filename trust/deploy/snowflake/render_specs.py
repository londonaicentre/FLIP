"""Render the SPCS service specifications for one FLIP trust (FLIP#1582).

Reads the trust's kit file (``trust/.env.<CODE>.<env>``) and writes one specification
per service in the naming contract into ``rendered/<CODE>.<env>/``, plus a
``manifest.json`` describing what was rendered (service names, compute pools, mapped
secret OBJECT NAMES, volumes and their read-only intent). The Makefile's ``up`` target
reads that manifest to know which SQL to emit, and the spec guards assert against it.

Nothing written here is a secret. Credentials reach containers only as Snowflake SECRET
objects, whose values ``make sync-kit`` writes; a kit value that is a credential is
never interpolated into a rendered file. The guards in ``tests/`` assert that directly.

Usage:
  python3 render_specs.py --kit GSTT --env production
  python3 render_specs.py --kit GSTT --env production --out-dir /tmp/specs
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import yaml_min  # noqa: E402
from kitfile import kit_path, read_env_vars, resolve_env  # noqa: E402
from naming import Names, NamingError  # noqa: E402
from spec_templates import build_all  # noqa: E402

REPO_ROOT = HERE.parents[2]

#: Where ``make mirror-images`` records the digest it pushed for each repository.
IMAGE_LOCK = "images.lock.json"

HEADER = """\
# ── Generated by render_specs.py - DO NOT edit by hand ──────────────────────
# SPCS service specification for '{service}' of FLIP trust {code} ({env}).
# Rendered from trust/.env.{code}.{env}. Contains NO secret values: credentials
# reach the container as Snowflake SECRET objects, written by `make sync-kit`.
# Regenerate with:
#   make -C trust/deploy/snowflake render KIT={code} PROD=<env>
"""


def load_digests(directory: Path) -> dict[str, str]:
    """Image digests recorded by ``make mirror-images``; empty when none were."""
    lock = directory / IMAGE_LOCK
    if not lock.exists():
        return {}
    try:
        data = json.loads(lock.read_text())
    except json.JSONDecodeError as e:
        sys.exit(f"❌ {lock} is not valid JSON ({e}). Re-run `make mirror-images`.")
    images = data.get("images", {})
    return {repo: entry.get("digest", "") for repo, entry in images.items()}


def render(kit: dict[str, str], code: str, env: str, out_dir: Path, digests: dict[str, str]) -> dict[str, Any]:
    """Write every service specification and the manifest. Returns the manifest."""
    names = Names(code)
    out_dir.mkdir(parents=True, exist_ok=True)
    # A stale spec from a previous render (an FL net removed from the kit, say) would
    # otherwise still be deployed by `up`, which walks the manifest - and still sit in
    # the directory an operator reads. Clear what we own, nothing else.
    for stale in out_dir.glob("*.yaml"):
        stale.unlink()

    services: list[dict[str, Any]] = []
    for item in build_all(kit, code, digests):
        path = out_dir / f"{item.name}.yaml"
        body = HEADER.format(service=item.name, code=names.code, env=env) + yaml_min.dump(item.spec)
        path.write_text(body)
        container = item.spec["spec"]["containers"][0]
        services.append(
            {
                "name": item.name,
                "sql_name": names.service(item.name),
                "kind": item.kind,
                "pool": item.pool,
                "spec_file": path.name,
                "image": container["image"],
                "secrets": sorted(entry["snowflakeSecret"]["objectName"] for entry in container.get("secrets", [])),
                "volumes": [volume["name"] for volume in item.spec["spec"].get("volumes", [])],
                "read_only_volumes": item.read_only_volumes,
                "endpoints": item.spec["spec"].get("endpoints", []),
            }
        )

    manifest: dict[str, Any] = {
        "code": names.code,
        "env": env,
        "database": names.database,
        "schema": "APP",
        "warehouse": names.warehouse,
        "image_repository": names.image_repository,
        "image_repository_path": names.image_repository_path,
        "pools": {"service": names.pool, "job": names.job_pool, "gpu": names.gpu_pool},
        "services": services,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Render SPCS service specs for a FLIP trust")
    parser.add_argument("--kit", required=True, help="Trust CODE (e.g. GSTT)")
    parser.add_argument(
        "--env",
        default=None,
        help="Kit-file env token (trust/.env.<KIT>.<token>). Required when PROD is set; the "
        "Makefile injects it from deploy/env_mode.mk. Default without PROD: development.",
    )
    parser.add_argument("--out-dir", type=Path, default=None, help="Output directory (default: rendered/<KIT>.<env>)")
    parser.add_argument(
        "--kit-file",
        type=Path,
        default=None,
        help="Read the kit from this file instead of trust/.env.<KIT>.<env> (tests, dry runs)",
    )
    args = parser.parse_args()

    env = resolve_env(args.env)
    try:
        names = Names(args.kit)
    except NamingError as e:
        sys.exit(f"❌ {e}")

    path = args.kit_file or kit_path(REPO_ROOT, args.kit, env)
    if not path.exists():
        sys.exit(
            f"❌ Kit file not found: {path}\n"
            "   Register the trust first:\n"
            f'     make new-trust TRUST_CODE={args.kit} TRUST_NAME="..."\n'
            f"     make -C deploy/providers/AWS register-trusts KIT={args.kit} PROD={env}\n"
            f"     make sync-trust-kit KIT={args.kit} PROD={env}"
        )
    kit = read_env_vars(path)
    out_dir = args.out_dir or HERE / "rendered" / f"{names.code}.{env}"
    digests = load_digests(HERE)
    manifest = render(kit, args.kit, env, out_dir, digests)

    print(f"🔧 Rendered {len(manifest['services'])} SPCS specs for {names.code} ({env})")
    print(f"   Kit file: {path}")
    print(f"   Output:   {out_dir}")
    if not digests:
        print("   ⚠  No images.lock.json - specs reference images by TAG. Run `make mirror-images`")
        print("      before deploying anything you intend to keep: a tag in the account repository")
        print("      can be moved, a digest cannot.")
    for service in manifest["services"]:
        print(f"   • {service['name']:<20} {service['kind']:<8} pool={service['pool']}")


if __name__ == "__main__":
    main()
