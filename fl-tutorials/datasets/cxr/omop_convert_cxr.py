"""Build the cxr_project OMOP tables from the DICOM metadata table.

Imported from ``londonaicentre/flip-omop-mock-data`` (FLIP#1092 wave 2). Behaviour is unchanged.

Unlike spleen, only the OMOP conversion is in-tree: the chest X-rays themselves are generated by a
synthetic model that lives outside this pipeline, in the private ``londonaicentre/xraycat`` repo.
The provenance this file records therefore starts at the DICOM metadata table, which is published
alongside its outputs on ``aicentreflip/trust-data`` and is what the verification gate replays.
"""

import argparse
import os
import shutil

import pandas as pd
from tqdm import tqdm
from utils.omop_ids import surrogate_ids
from utils.omop_mappings import (
    EHR_TYPE_CONCEPT_ID,
    INPATIENT_VISIT_CONCEPT_ID,
    MAPPING_ANATOMIC_SITE,
    MAPPING_CXR,
    MAPPING_FINDING,
    MAPPING_MODALITY,
    MAPPING_SEX,
    MAPPING_YES_NO,
    UNKNOWN_CONCEPT_ID,
)
from utils.omop_schemas import schemas


def parse_args():
    args = argparse.ArgumentParser()
    args.add_argument(
        "--dataset_table", type=str, default="data/cxr_metadata.csv", help="Path to the Dicom data table."
    )
    args.add_argument("--omop_root", type=str, default=".", help="Path to the output OMOP root folder.")
    args.add_argument(
        "--save_dicom", action="store_true", help="Whether to save the DICOM files into trust specific folders."
    )
    args = args.parse_args()

    return args


def get_concepts_from_pathologies(pathologies_str: str, conditioning: str) -> list[dict]:
    """Convert `pathologies` and `conditioning` values from the synthetic x-ray table to a dictionary of concept IDs.

    Args:
        pathologies (str): comma-delimited list of findings, e.g. "no_pleural_effusion,edema".
        conditioning (str): full text description of the findings, e.g. "No pleural effusion. Right-sided pulmonary
        edema."

    Returns:
        list[dict]: List of dictionaries, one for each pathology, with keys:
                    - 'concept' (finding concept ID)
                    - 'location' (anatomy concept ID)
                    - 'negative' (1 if finding is absent, 0 if present).
    """

    output_pathology_entries = []
    pathologies = pathologies_str.split(",")
    conditioning = conditioning.lower()
    for pathology in pathologies:
        # Since the description is basic, we know that right lesions have 'right-sided' or 'right sided', 'left-sided'
        # etc.
        # This is an assumption we make in the case of this specific synthetic X-Ray dataset.
        if "right-sided" in conditioning or "right sided" in conditioning:
            location = "right lung"
        elif "left-sided" in conditioning or "left sided" in conditioning:
            location = "left lung"
        elif "congestive heart failure" in conditioning:
            location = "heart"
        else:
            location = "both lungs"

        if pathology == "no_finding":
            pathology_description = "normal lungs"
        else:
            pathology_description = pathology.replace("no_", "").replace("_", " ")
            if "edema" in pathology_description:
                pathology_description = "pulmonary edema"

        try:
            pathology_entry = {
                "concept": MAPPING_FINDING[pathology_description],
                "location": MAPPING_ANATOMIC_SITE[location],
                "negative": 1 if "no_" in pathology else 0,
            }
        except Exception as e:
            pathology_entry = {}
            print(e)

        output_pathology_entries.append(pathology_entry)

    return output_pathology_entries


TRUSTS = {
    "trust_1": ("Dummy"),
    "trust_2": ("Dummy"),
}
DICOM_FOLDER_PATH = "./dicom_output"
PROJECT = "cxr_project"


def nhs_number_to_integer(s):
    """Converts the PatientID (NHS number e.g. '123 456 789') to an integer"""
    return int(f"{s.replace(' ', '')[:9]}")


def transform_dicom_metadata_to_omop_tables(csv_file_path: str, omop_root: str = "") -> dict[str, pd.DataFrame]:
    """
    Convert a dicom_metadata.csv file to OMOP tables
    Returns a dictionary of OMOP tables by name.
    """
    combined_tables = {}

    if omop_root:
        os.makedirs(omop_root, exist_ok=True)

    # Read all CSV columns as strings to avoid issues with leading zeros
    df = pd.read_csv(csv_file_path, dtype=str)

    # Split the data into trusts
    trust_key_mapping = {number: trust for number, trust in enumerate(TRUSTS.keys())}
    df["trust_index"] = df.index % len(TRUSTS)
    df["trust"] = df["trust_index"].map(trust_key_mapping)

    # ----------------------------------------------
    # ---------------- Person table ----------------
    # ----------------------------------------------
    person = pd.DataFrame()
    person["person_id"] = df["PatientID"].apply(nhs_number_to_integer)
    person["gender_concept_id"] = df["PatientSex"].map(MAPPING_SEX)
    person["birth_datetime"] = pd.to_datetime(df["PatientBirthDate"], format="%Y%m%d")
    person["year_of_birth"] = person["birth_datetime"].dt.year.astype(
        "int64"
    )  # pandas default is int32 but pandera expects int64
    person["month_of_birth"] = person["birth_datetime"].dt.month.astype("int64")
    person["day_of_birth"] = person["birth_datetime"].dt.day.astype("int64")
    person["race_concept_id"] = UNKNOWN_CONCEPT_ID  # not nullable; set as unknown
    person["ethnicity_concept_id"] = UNKNOWN_CONCEPT_ID  # not nullable; set as unknown
    person["gender_source_value"] = df["PatientSex"]
    person["person_source_value"] = df["PatientID"]

    # Validate, add trust column, and store
    person = schemas["person"].validate(person)
    print("Created and validated table: person")
    person["trust"] = df["trust"]
    combined_tables["person"] = person

    # ----------------------------------------------
    # --------- Visit Occurrence table -------------
    # ----------------------------------------------
    visit_occurrence = pd.DataFrame()
    visit_occurrence["visit_occurrence_id"] = surrogate_ids(PROJECT, len(df))
    visit_occurrence["person_id"] = person["person_id"]
    visit_occurrence["visit_concept_id"] = (
        INPATIENT_VISIT_CONCEPT_ID  # Inpatient visit (https://athena.ohdsi.org/search-terms/terms/9201)
    )
    visit_occurrence["visit_start_date"] = pd.to_datetime(df["StudyDate"], format="%Y%m%d")
    df["StudyTime"] = df["StudyTime"].str.zfill(6)
    visit_occurrence["visit_start_datetime"] = pd.to_datetime(df["StudyDate"] + df["StudyTime"], format="%Y%m%d%H%M%S")
    visit_occurrence["visit_end_date"] = visit_occurrence["visit_start_date"]
    visit_occurrence["visit_end_datetime"] = visit_occurrence["visit_start_datetime"]
    visit_occurrence["visit_type_concept_id"] = (
        EHR_TYPE_CONCEPT_ID  # EHR, copying https://github.com/paulnagy/DICOM2OMOP/blob/main/demonstration/transform_imaging_metadata.ipynb
    )

    # Validate, add trust column, and store
    visit_occurrence = schemas["visit_occurrence"].validate(visit_occurrence)
    print("Created and validated table: visit_occurrence")
    visit_occurrence["trust"] = df["trust"]
    combined_tables["visit_occurrence"] = visit_occurrence

    # ----------------------------------------------
    # --------- Procedure Occurrence table ---------
    # ----------------------------------------------
    procedure_occurrence = pd.DataFrame()
    procedure_occurrence["procedure_occurrence_id"] = surrogate_ids(PROJECT, len(df))
    procedure_occurrence["person_id"] = person["person_id"]
    procedure_occurrence["procedure_concept_id"] = MAPPING_CXR["plain_xray"]
    procedure_occurrence["procedure_date"] = pd.to_datetime(df["StudyDate"], format="%Y%m%d")
    procedure_occurrence["procedure_datetime"] = pd.to_datetime(
        df["StudyDate"] + df["StudyTime"], format="%Y%m%d%H%M%S"
    )
    procedure_occurrence["procedure_type_concept_id"] = (
        EHR_TYPE_CONCEPT_ID  # EHR, copying https://github.com/paulnagy/DICOM2OMOP/blob/main/demonstration/transform_imaging_metadata.ipynb
    )
    procedure_occurrence["quantity"] = 1  # Could be number of series if available?
    procedure_occurrence["visit_occurrence_id"] = visit_occurrence["visit_occurrence_id"]
    procedure_occurrence["procedure_source_value"] = df["StudyDescription"]

    # Validate, add trust column, and store
    procedure_occurrence = schemas["procedure_occurrence"].validate(procedure_occurrence)
    print("Created and validated table: procedure_occurrence")
    procedure_occurrence["trust"] = df["trust"]
    combined_tables["procedure_occurrence"] = procedure_occurrence

    # ----------------------------------------------
    # --------- Image Occurrence table -------------
    # ----------------------------------------------
    image_occurrence = pd.DataFrame()
    image_occurrence["image_occurrence_id"] = surrogate_ids(PROJECT, len(df))
    image_occurrence["person_id"] = person["person_id"]
    image_occurrence["procedure_occurrence_id"] = procedure_occurrence["procedure_occurrence_id"]
    image_occurrence["visit_occurrence_id"] = visit_occurrence["visit_occurrence_id"]
    image_occurrence["anatomic_site_concept_id"] = MAPPING_CXR["lung_structure"]  # Lung structure  # CSV does have BPE
    # "FileName" in the cxr metadata table holds a bare filename, not a path, so dirname() yields ""
    # and local_path is blank for every row. (Upstream this comment said "spleen metadata CSV" — a
    # copy-paste from omop_convert_spleen.py. The behaviour it describes is right; the dataset was not.)
    image_occurrence["local_path"] = df["FileName"].apply(os.path.dirname)
    image_occurrence["image_occurrence_date"] = pd.to_datetime(df["StudyDate"], format="%Y%m%d")
    if "StudyInstanceUID" in df.columns:
        image_occurrence["image_study_uid"] = df["StudyInstanceUID"]
    else:
        image_occurrence["image_study_uid"] = df[
            "SOPInstanceUID"
        ]  # Hack: this actually represents a single image, not the study, but the field is not nullable
    image_occurrence["image_series_uid"] = df["SeriesInstanceUID"]
    image_occurrence["modality_concept_id"] = df["Modality"].map(MAPPING_MODALITY)
    image_occurrence["accession_id"] = df[
        "AccessionNumber"
    ]  # Not in the official OMOP schema; hope to retire later and use StudyInstanceUID instead

    # Validate, add trust column, and store
    image_occurrence = schemas["image_occurrence"].validate(image_occurrence)
    print("Created and validated table: image_occurrence")
    image_occurrence["trust"] = df["trust"]
    combined_tables["image_occurrence"] = image_occurrence

    # ----------------------------------------------
    # ---- Image Feature and Observation tables ----
    # ----------------------------------------------
    image_feature_ms = image_occurrence[
        [
            "person_id",
            "image_occurrence_id",
            "image_occurrence_date",
            "accession_id",
            "trust",
        ]
    ].copy()

    rows_image_feature = []
    rows_observation = []
    cells_trust = []
    for _, row in tqdm(
        image_feature_ms.iterrows(), total=len(image_feature_ms), desc="image features and observations"
    ):
        accession_id = row["accession_id"]
        # Find conditioning and pathology strings, using first entry in case of multiple occurrences of the accession
        # number
        conditioning = df.loc[df["AccessionNumber"].eq(accession_id), "conditioning"].iloc[0]
        pathologies = df.loc[df["AccessionNumber"].eq(accession_id), "pathologies"].iloc[0]

        # Process pathologies and conditioning to get individual sets of concepts
        finding_entries = get_concepts_from_pathologies(pathologies, conditioning)

        # Expand each row of image occurrence according to the number of pathology entries
        for entry_id, entry in enumerate(finding_entries):
            # ID is a combination of the image_occurrence_id and the individual finding
            # Use the same ID for image_feature and observation tables for simplicity
            # NOTE: unlike the three ids above, this one is DERIVED, not allocated — the
            # image_occurrence_id with a two-digit finding index appended. So it lands around 100,000,000
            # (1,000,001 -> 100,000,100), outside cxr_project's reserved 1M block and outside every other
            # project's. Nothing collides today (spleen's image_feature_ids sit at 2,000,001+), but
            # utils.omop_ids does not describe this band, so do not assume it is reserved. Changing the
            # scheme would change published ids, so it stays as-is and is documented instead.
            this_id = int(f"{row['image_occurrence_id']}{entry_id:02d}")

            # Expand image_feature rows
            row_if = pd.Series()
            row_if["image_feature_id"] = this_id
            row_if["person_id"] = row["person_id"]
            row_if["image_occurrence_id"] = row["image_occurrence_id"]
            row_if["image_feature_concept_id"] = entry["concept"]
            row_if["anatomic_site_concept_id"] = entry["location"]
            row_if["image_feature_type_concept_id"] = MAPPING_CXR["ehr_radiology_report"]  # EHR Radiology Report
            row_if["image_feature_event_field_concept_id"] = MAPPING_CXR["observation"]
            row_if["image_feature_event_id"] = this_id  # Reference to observation_id
            rows_image_feature.append(row_if)

            # For each row in feature we register observation table entry with yes/no.
            row_ob = pd.Series()
            row_ob["observation_id"] = this_id
            row_ob["person_id"] = row["person_id"]
            row_ob["observation_concept_id"] = entry["concept"]
            row_ob["observation_type_concept_id"] = MAPPING_CXR["ehr_radiology_report"]
            row_ob["observation_date"] = row["image_occurrence_date"]
            row_ob["value_as_concept_id"] = MAPPING_YES_NO["no"] if entry["negative"] else MAPPING_YES_NO["yes"]
            row_ob["value_as_number"] = 0.0 if entry["negative"] else 1.0
            rows_observation.append(row_ob)

            cells_trust.append(row["trust"])

    # Convert lists of series to dataframes, one row per series
    image_feature = pd.DataFrame(rows_image_feature)
    image_feature = schemas["image_feature"].validate(image_feature)
    print("Created and validated table: image_feature")
    image_feature["trust"] = cells_trust
    combined_tables["image_feature"] = image_feature

    observation = pd.DataFrame(rows_observation)
    observation = schemas["observation"].validate(observation)
    print("Created and validated table: observation")
    observation["trust"] = cells_trust
    combined_tables["observation"] = observation

    # Save the tables to CSV files
    os.makedirs(f"{omop_root}/omop/{PROJECT}", exist_ok=True)
    for table_name, table_df in combined_tables.items():
        table_df.to_csv(f"{omop_root}/omop/{PROJECT}/{table_name}.csv", index=False)

    return combined_tables


def split_data_into_trusts_and_copy_dicoms(
    combined_tables: dict[str, pd.DataFrame],
    omop_root: str,
    copy_dicom: bool = False,
    overwrite: bool = False,
) -> dict[str, dict[str, pd.DataFrame]]:
    """
    Split the data into trust specific folders.
        * The OMOP CSVs are split and saved into trust specific folders.
        * [Optional] DICOMs are copied to the trust specific folders.
    """
    tables_by_trust: dict[str, dict[str, pd.DataFrame]] = {trust: {} for trust in TRUSTS.keys()}

    for trust in TRUSTS.keys():
        trust_folder_name = f"{omop_root}/omop/{trust}/{PROJECT}"
        trust_dicom_folder_name = f"{trust_folder_name}/dicoms"

        # Delete the trust folder if it already exists
        if overwrite:
            if os.path.isdir(trust_folder_name):
                shutil.rmtree(trust_folder_name)

        os.makedirs(trust_folder_name, exist_ok=True)

        # Split tables and save to CSV
        for table_name, combined_table in combined_tables.items():
            trust_table = combined_table.loc[combined_table["trust"].eq(trust), :].drop(columns="trust")
            schemas[table_name].validate(trust_table)
            trust_table.to_csv(f"{trust_folder_name}/{table_name}.csv", index=False)
            tables_by_trust[trust][table_name] = trust_table

        # Copy DICOM files to trust folder
        if copy_dicom:
            os.makedirs(trust_dicom_folder_name)
            image_occurrence = tables_by_trust[trust]["image_occurrence"]
            for _, row in image_occurrence.iterrows():
                # Retrieve and check source DICOM folder path
                subject_dicom_source_folder = str(row["local_path"])
                if not subject_dicom_source_folder:
                    raise ValueError("Dicom folder path is blank")
                if not os.path.isdir(subject_dicom_source_folder):
                    raise FileNotFoundError(f"Source DICOM folder not found: {subject_dicom_source_folder}")

                # Construct and check subject_name
                subject_name = os.path.basename(subject_dicom_source_folder)
                if not subject_name:
                    raise ValueError(
                        f"Subject name could not be determined from DICOM folder path: {subject_dicom_source_folder}"
                    )

                # Retrieve accession_id and confirm it is not blank
                accession_id = row["accession_id"]
                if not accession_id:
                    raise ValueError(f"Accession ID is blank for {subject_dicom_source_folder}")

                # Copy all dicoms for this subject to the trust dicom folder under a subject folder
                trust_subject_dicom_folder_name = f"{trust_dicom_folder_name}/{accession_id}_{subject_name}"
                # subject_dicom_source_folder by definition is a folder not a file
                shutil.copytree(subject_dicom_source_folder, trust_subject_dicom_folder_name)
                print(
                    f"Copied dicoms from {accession_id} ({subject_dicom_source_folder}) to "
                    f"{trust_subject_dicom_folder_name}"
                )

            trust_dicom_count = len(os.listdir(trust_dicom_folder_name))
            print(f"trust_dicom_count: {trust_dicom_count}")
            print(f"dicom datasets expected: {len(image_occurrence)}")

    return tables_by_trust


if __name__ == "__main__":
    args = parse_args()

    # Create tables
    combined_tables = transform_dicom_metadata_to_omop_tables(args.dataset_table, args.omop_root)
    print("Created combined tables and saved to CSV.")

    # Split data into trusts and copy dicoms
    tables_by_trust = split_data_into_trusts_and_copy_dicoms(
        combined_tables, omop_root=args.omop_root, copy_dicom=args.save_dicom, overwrite=True
    )
    print("Split data into trusts and saved to CSV.")

    # Review results
    for trust, tables in tables_by_trust.items():
        for table_name in ["person", "visit_occurrence", "procedure_occurrence", "image_occurrence"]:
            print(f"Trust: {trust}. Table: {table_name}.")
            print(tables[table_name].head())
            print("")
